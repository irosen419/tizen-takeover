/*
 * Puts the Architecture page into the Layout Studio: node studio/build-architecture.js
 *
 * The page is written in studio/architecture/ (arch.css, arch.js, data.json). The
 * Studio is published as one file, so this copies those three into the marked
 * places in studio/layout-studio.html. Run it after editing any of them, then
 * `node dev/architecture-test.js`, then republish the Studio. Pass --check to
 * only report whether the Studio is up to date (exit 1 if not).
 *
 * It also writes the TV's copy of the same data (app/widgets/architecture-data.js,
 * `var HUB_ARCH = {...};`, loaded by the Architecture widget only when it is first
 * opened) and the small summary the widget's tile draws without that file (the
 * status counts and the seven Big picture boxes, between the ARCH-SUMMARY markers
 * in app/widgets/architecture.js). --check verifies both as well. data.json stays
 * the single source.
 *
 * Both copies also carry `codemap`: docs/CODE-MAP.md read by studio/codemap.js and
 * matched to every part's files (the drawer's "Code map" section). Editing the code
 * map therefore needs this script run again; --check (and dev/codemap-test.js) fail
 * until it is.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const html = path.join(dir, 'layout-studio.html');
const read = (f) => fs.readFileSync(path.join(dir, 'architecture', f), 'utf8');
const codemap = require('./codemap');
// data.json plus the code map: what both pages draw.
const full = () => codemap.attach(JSON.parse(read('data.json')), fs.readFileSync(path.join(dir, '..', 'docs', 'CODE-MAP.md'), 'utf8'));

function build() {
  let s = fs.readFileSync(html, 'utf8');
  const data = JSON.stringify(full());
  // "</" inside JSON in a script tag could end it early; "<!--" can start a comment.
  const safe = data.replace(/<\//g, '<\\/').replace(/<!--/g, '<\\!--');
  const parts = [
    ['/*ARCH-CSS-BEGIN*/', '/*ARCH-CSS-END*/', '\n' + read('arch.css') + '\n'],
    ['<!-- ARCH-MARKUP-BEGIN -->', '<!-- ARCH-MARKUP-END -->', '\n      <div id="archView" aria-label="Architecture"></div>\n      <script type="application/json" id="archData">' + safe + '</script>\n      '],
    ['<!-- ARCH-JS-BEGIN -->', '<!-- ARCH-JS-END -->', '\n<script>\n' + read('arch.js') + '</script>\n']
  ];
  parts.forEach(([a, b, body]) => {
    const i = s.indexOf(a), j = s.indexOf(b);
    if (i < 0 || j < i) throw new Error('marker missing: ' + a);
    s = s.slice(0, i + a.length) + body + s.slice(j);
  });
  return s;
}

/* ---------- the TV's copy ---------- */

const tvData = path.join(dir, '..', 'app', 'widgets', 'architecture-data.js');
const tvWidget = path.join(dir, '..', 'app', 'widgets', 'architecture.js');
const SUM_BEGIN = '/*ARCH-SUMMARY-BEGIN*/';
const SUM_END = '/*ARCH-SUMMARY-END*/';

// JSON for a script that old Chromium parses: pure ASCII, so no file encoding or
// line separator (U+2028 and U+2029) can break a string.
function ascii(json) {
  return json.replace(/[\u0080-\uffff]/g, (c) => '\\u' + ('0000' + c.charCodeAt(0).toString(16)).slice(-4));
}

function buildTvData() {
  const d = full();
  return '/* Generated by node studio/build-architecture.js from studio/architecture/data.json. Do not edit.\n' +
    '   Loaded by app/widgets/architecture.js the first time the widget opens full screen. */\n' +
    'var HUB_ARCH = ' + ascii(JSON.stringify(d)) + ';\n';
}

// What the tile needs without the big file: status counts (every part, not the
// seven group headings) and the Big picture boxes with how many parts each holds.
function buildSummary() {
  const d = JSON.parse(read('data.json'));
  const total = { live: 0, unverified: 0, draft: 0, planned: 0 };
  const groups = {};
  d.tree.forEach((g) => {
    const c = { live: 0, unverified: 0, draft: 0, planned: 0 };
    (function walk(n) {
      if (c.hasOwnProperty(n.status)) { c[n.status]++; total[n.status]++; }
      (n.children || []).forEach(walk);
    })(g);
    groups[g.id] = c;
  });
  const o = d.overview || {};
  const sum = {
    asOf: d.asOf,
    counts: total,
    w: o.w, h: o.h,
    boxes: (o.boxes || []).map((b) => ({ group: b.group, x: b.x, y: b.y, w: b.w, h: b.h, counts: groups[b.group] }))
  };
  return SUM_BEGIN + '\n  var SUMMARY = ' + ascii(JSON.stringify(sum)) + ';\n  ' + SUM_END;
}

function buildWidget() {
  const s = fs.readFileSync(tvWidget, 'utf8');
  const i = s.indexOf(SUM_BEGIN), j = s.indexOf(SUM_END);
  if (i < 0 || j < i) throw new Error('marker missing in app/widgets/architecture.js: ' + SUM_BEGIN);
  return s.slice(0, i) + buildSummary() + s.slice(j + SUM_END.length);
}

const out = build();
const tvOut = buildTvData();
const wOut = buildWidget();
const cur = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
if (process.argv.includes('--check')) {
  const same = out === cur(html);
  const tvSame = tvOut === cur(tvData) && wOut === cur(tvWidget);
  console.log(same ? 'Studio is up to date with studio/architecture/' : 'Studio is OUT OF DATE: run node studio/build-architecture.js');
  console.log(tvSame ? 'The TV data and tile summary are up to date' : 'The TV data or tile summary is OUT OF DATE: run node studio/build-architecture.js');
  process.exit(same && tvSame ? 0 : 1);
}
fs.writeFileSync(html, out);
fs.writeFileSync(tvData, tvOut);
fs.writeFileSync(tvWidget, wOut);
console.log('Studio updated (' + out.length + ' bytes); TV data ' + tvOut.length + ' bytes; tile summary updated');
