#!/usr/bin/env node
'use strict';
/*
 * Moods for Home Assistant: writes the YAML Ian pastes or installs in HA, from
 * pi/moods/moods.json (plan section 5). Holds no entity id, address or token:
 * the package names the hub as HUB_BASE (the Pi helper fills it from the
 * existing Home Hub package) and the token as !secret hub_lights_auth.
 *
 *   node dev/moods-ha.js --out <dir>              every file
 *   node dev/moods-ha.js --out <dir> --stage a    moods-dashboard.yaml, moods-test.sh
 *   node dev/moods-ha.js --out <dir> --stage b    moods-package.yaml, moods-dashboard-b.yaml
 *
 * Stage A: a new "Wall moods" dashboard. Every button calls the existing
 * rest_command.hub_command with type "mood" (no HA file change, no restart).
 * Stage B: a package (sensor.wall_mood, script.wall_mood_<id>, select.wall_mood)
 * and the same dashboard with a "Now" line and the select.
 *
 * The "mood" command's data (handled on the Pi, plan 4.3):
 *   { "id": "<mood id>" }       set a mood            (POST /api/moods/set)
 *   { "id": "off" }             the wall as it was     (POST /api/moods/off)
 *   { "bri": 60 }               brightness, no id      (POST /api/moods/bri)
 *   { "event": "thunder" }      one thunder cue        (POST /api/moods/event)
 * Thunder and brightness ride on the same command so that no new rest_command
 * is ever generated (stage A must need no HA file change).
 *
 * Exports dashboardYaml(catalog, opt), packageYaml(catalog, opt), testScript(catalog).
 * Tests: node dev/moods-ha-test.js
 */
const fs = require('fs');
const path = require('path');

const COMMAND = 'rest_command.hub_command';
const BRIGHTNESS = [20, 40, 60, 80, 100];
const BRI_ICONS = ['mdi:brightness-3', 'mdi:brightness-4', 'mdi:brightness-5', 'mdi:brightness-6', 'mdi:brightness-7'];
const GROUPS = [['wall', 'Whole wall'], ['vases', 'Vases']];
const HOLD_DEFAULT = 8;

const q = (s) => JSON.stringify(String(s));
const slug = (id) => {
  const s = String(id).replace(/-/g, '_');
  if (!/^[a-z0-9_]+$/.test(s)) throw new Error('mood id cannot be an HA id: ' + id);
  return s;
};
const header = (lines) => lines.map((l) => ('# ' + l).replace(/\s+$/, '')).join('\n') + '\n';

// The moods HA shows, in catalog order: ha.expose true and not hidden.
function exposed(catalog) {
  return (catalog.moods || [])
    .filter((m) => !m.hidden && m.ha && m.ha.expose === true)
    .slice()
    .sort((a, b) => a.n - b.n);
}

function button(ind, name, icon, data) {
  const p = ' '.repeat(ind);
  return [
    p + '- type: button',
    p + '  name: ' + q(name),
    p + '  icon: ' + icon,
    p + '  show_state: false',
    p + '  tap_action:',
    p + '    action: perform-action',
    p + '    perform_action: ' + COMMAND,
    p + '    data:',
    p + '      type: mood',
    p + '      data: ' + JSON.stringify(data),
    p + '  grid_options:',
    p + '    columns: 4',
    p + '    rows: 2'
  ];
}

function heading(ind, text) {
  const p = ' '.repeat(ind);
  return [p + '- type: heading', p + '  heading: ' + q(text)];
}

// The "Now" line for stage B (reads sensor.wall_mood).
function nowCard(ind) {
  const p = ' '.repeat(ind);
  const s = "'sensor.wall_mood'";
  return [
    p + '- type: markdown',
    p + '  grid_options:',
    p + '    columns: 12',
    p + '  content: |-',
    p + "    {% set id = states(" + s + ") %}",
    p + "    {% if id in ['unknown', 'unavailable'] %}### Wall not answering",
    p + "    The hub has not answered for a while.{% elif id == 'off' %}### Off",
    p + "    The wall is as it was before the last mood.{% else %}### {{ state_attr(" + s + ", 'name') }} · {{ state_attr(" + s + ", 'bri') }}%",
    p + "    {{ 'Pi-drawn' if state_attr(" + s + ", 'path') == 'pi-drawn' else 'WLED effects' }}{% if state_attr(" + s + ", 'stale') %} · Changed somewhere else{% endif %}{% endif %}",
    p + '- type: entities',
    p + '  grid_options:',
    p + '    columns: 12',
    p + '  entities:',
    p + '    - entity: select.wall_mood',
    p + '      name: "Wall mood"'
  ];
}

function dashboardYaml(catalog, opt) {
  const stage = (opt && opt.stage) === 'b' ? 'b' : 'a';
  const moods = exposed(catalog);
  const out = [];
  out.push(header([
    'Wall moods dashboard (sections view), stage ' + stage.toUpperCase() + '. Generated by dev/moods-ha.js from',
    'pi/moods/moods.json; do not edit by hand, run the generator again.',
    'New dashboard "Wall moods", sidebar icon mdi:wall-sconce-flat-variant, url path wall-moods;',
    'paste this in its raw configuration editor. Undo: delete the dashboard.',
    'Every button calls the existing rest_command.hub_command with type "mood":',
    '  {"id": "<mood>"} sets a mood, {"id": "off"} puts the wall back as it was,',
    '  {"bri": 60} changes the brightness of the mood on now, {"event": "thunder"}',
    '  sends one thunder cue (the hub decides what the mood on now does with it).',
    'No new rest_command: Thunder and brightness use the same command on purpose.',
    stage === 'a'
      ? 'Stage A needs no HA file change and no restart.'
      : 'Stage B needs moods-package.yaml installed first (sensor.wall_mood, select.wall_mood).',
    'A mood also sets the lamp and bars when the hub pairs them (its default; skipped while music lights are on).'
  ]));
  out.push('title: "Wall moods"');
  out.push('views:');
  out.push('  - title: "Wall moods"');
  out.push('    path: wall-moods');
  out.push('    icon: mdi:wall-sconce-flat-variant');
  out.push('    type: sections');
  out.push('    max_columns: 3');
  out.push('    sections:');
  // Controls: (Now and the select), Off, Thunder, brightness.
  out.push('      - type: grid');
  out.push('        cards:');
  Array.prototype.push.apply(out, heading(10, 'Plant wall'));
  if (stage === 'b') Array.prototype.push.apply(out, nowCard(10));
  Array.prototype.push.apply(out, button(10, 'Off', 'mdi:power', { id: 'off' }));
  Array.prototype.push.apply(out, button(10, 'Thunder', 'mdi:weather-lightning', { event: 'thunder' }));
  Array.prototype.push.apply(out, heading(10, 'Brightness'));
  BRIGHTNESS.forEach((b, i) => {
    Array.prototype.push.apply(out, button(10, b + '%', BRI_ICONS[i], { bri: b }));
  });
  GROUPS.forEach((g) => {
    const list = moods.filter((m) => m.group === g[0]);
    if (!list.length) return;
    out.push('      - type: grid');
    out.push('        cards:');
    Array.prototype.push.apply(out, heading(10, g[1]));
    list.forEach((m) => {
      Array.prototype.push.apply(out, button(10, m.name, m.ha.icon, { id: m.id }));
    });
  });
  const stray = moods.filter((m) => !GROUPS.some((g) => g[0] === m.group));
  if (stray.length) throw new Error('mood group not shown in HA: ' + stray[0].id);
  return out.join('\n') + '\n';
}

function packageYaml(catalog, opt) {
  const scan = (opt && opt.scanInterval) || 10;
  const moods = exposed(catalog);
  const names = [['off', 'Off']].concat(moods.map((m) => [m.id, m.name]));
  const out = [];
  out.push(header([
    'Wall moods package, stage B. Generated by dev/moods-ha.js from pi/moods/moods.json.',
    'Adds sensor.wall_mood (what the plant wall shows, every ' + scan + ' s), one script per mood',
    '(script.wall_mood_<id>, plus script.wall_mood_off) for automations and voice, and',
    'select.wall_mood ("Wall mood"), whose state follows the sensor and whose choice runs',
    'the script. It defines no rest_command: the scripts call the existing',
    'rest_command.hub_command (from the Home Hub package) with type "mood".',
    'HUB_BASE: the same address the Home Hub package already uses (scheme, host and port',
    'only). Authorization is the existing secret hub_lights_auth.',
    'Install: copy into the packages folder (Ian\'s OK first), check the configuration,',
    'reload YAML (or restart if a new include line was needed). Undo: remove this file,',
    'reload or restart.'
  ]));
  out.push('rest:');
  out.push('  - resource: HUB_BASE/api/moods/now');
  out.push('    scan_interval: ' + scan);
  out.push('    timeout: 4');
  out.push('    headers:');
  out.push('      Authorization: !secret hub_lights_auth');
  out.push('    sensor:');
  out.push('      - name: "Wall mood"');
  out.push('        unique_id: wall_mood');
  out.push('        icon: mdi:wall-sconce-flat-variant');
  out.push('        value_template: "{{ value_json.id }}"');
  out.push('        json_attributes: [name, bri, path, stale]');
  out.push('');
  out.push('script:');
  names.forEach((n) => {
    const m = moods.find((x) => x.id === n[0]);
    out.push('  wall_mood_' + slug(n[0]) + ':');
    out.push('    alias: ' + q('Wall mood ' + n[1]));
    out.push('    icon: ' + (m ? m.ha.icon : 'mdi:power'));
    out.push('    mode: restart');
    out.push('    sequence:');
    out.push('      - action: ' + COMMAND);
    out.push('        data:');
    out.push('          type: mood');
    out.push('          data: ' + JSON.stringify({ id: n[0] }));
  });
  out.push('');
  const dict = '{' + names.map((n) => JSON.stringify(n[0]) + ': ' + JSON.stringify(n[1])).join(', ') + '}';
  out.push('template:');
  out.push('  - select:');
  out.push('      - name: "Wall mood"');
  out.push('        unique_id: wall_mood_select');
  out.push('        icon: mdi:wall-sconce-flat-variant');
  out.push('        availability: "{{ states(\'sensor.wall_mood\') not in [\'unknown\', \'unavailable\'] }}"');
  out.push('        state: >-');
  out.push('          {% set m = ' + dict + ' %}');
  out.push("          {% set id = states('sensor.wall_mood') %}");
  out.push("          {{ m[id] if id in m else '' }}");
  out.push('        options: >-');
  out.push('          {{ ' + JSON.stringify(names.map((n) => n[1])) + ' }}');
  out.push('        select_option:');
  out.push('          - variables:');
  out.push('              ids:');
  // Values quoted: a bare off is a boolean in YAML.
  names.forEach((n) => out.push('                ' + q(n[1]) + ': ' + q(slug(n[0]))));
  out.push('          - action: script.turn_on');
  out.push('            target:');
  out.push('              entity_id: "script.wall_mood_{{ ids[option] }}"');
  return out.join('\n') + '\n';
}

function testScript(catalog) {
  const ids = exposed(catalog).map((m) => m.id);
  const rows = [];
  for (let i = 0; i < ids.length; i += 4) rows.push(ids.slice(i, i + 4).join(' '));
  return [
    '#!/bin/sh',
    '# Try each wall mood through the hub, then put the wall back as it was.',
    '# Ian must be watching the wall: it changes every few seconds.',
    '# Run on the Pi:  sh moods-test.sh [seconds per mood]   (default ' + HOLD_DEFAULT + ')',
    '# Uses ./hub in the repo\'s pi folder (HUB_DIR to change it), always with --no-pair,',
    '# so the lamp and bars never change. Prints only mood ids and ok/failed, one line each.',
    '# Ends (and on Ctrl-C) with ./hub moods off. Generated by dev/moods-ha.js.',
    'set -u',
    'HOLD=${1:-' + HOLD_DEFAULT + '}',
    'HUB_DIR=${HUB_DIR:-$HOME/code/tizen-takeover/pi}',
    'cd "$HUB_DIR" || { echo "No hub folder; set HUB_DIR"; exit 1; }',
    'MOODS="' + rows.join('\n') + '"',
    '',
    'off() {',
    '  if ./hub moods off >/dev/null 2>&1; then echo "ok       off"; else echo "failed   off (run ./hub moods off)"; fi',
    '}',
    "trap 'off; exit 1' INT TERM",
    '',
    'for m in $MOODS; do',
    '  if ./hub moods set "$m" --no-pair >/dev/null 2>&1; then',
    '    echo "ok       $m"; sleep "$HOLD"',
    '  else',
    '    echo "failed   $m"',
    '  fi',
    'done',
    'off',
    ''
  ].join('\n');
}

// { file name: text } for a stage ('a', 'b' or null = all).
function files(catalog, stage) {
  const out = {};
  if (!stage || stage === 'a') {
    out['moods-dashboard.yaml'] = dashboardYaml(catalog, { stage: 'a' });
    out['moods-test.sh'] = testScript(catalog);
  }
  if (!stage || stage === 'b') {
    out['moods-package.yaml'] = packageYaml(catalog, {});
    out['moods-dashboard-b.yaml'] = dashboardYaml(catalog, { stage: 'b' });
  }
  return out;
}

function main(argv) {
  const at = (n) => { const i = argv.indexOf('--' + n); return i >= 0 ? argv[i + 1] : undefined; };
  const dir = at('out');
  const stage = at('stage');
  if (!dir || (stage !== undefined && stage !== 'a' && stage !== 'b')) {
    console.error('Use: node dev/moods-ha.js --out <dir> [--stage a|b]');
    process.exit(2);
  }
  const catalog = require('../pi/moods/catalog.js').load().catalog;
  fs.mkdirSync(dir, { recursive: true });
  const f = files(catalog, stage);
  Object.keys(f).forEach((name) => {
    const p = path.join(dir, name);
    fs.writeFileSync(p, f[name]);
    if (/\.sh$/.test(name)) fs.chmodSync(p, 0o755);
    console.log('wrote ' + name);
  });
}

module.exports = { dashboardYaml, packageYaml, testScript, files, exposed, slug, COMMAND, BRIGHTNESS };

if (require.main === module) main(process.argv.slice(2));
